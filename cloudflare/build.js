// npm run build:cloudflare: prepares the files the Cloudflare deployment needs (neither folder is committed).
//   cloudflare/site/                   the page's files: index.html (fog.html), rules.js (fog_logic.js for the
//                                      browser) and _headers
//   cloudflare/generated/bingosync.mjs BingoSync's generator as a module for the Worker
// Run `npm run fetch-generator` first: it downloads BingoSync's generator (see load_generator.js).
"use strict";

const fs = require("fs");
const path = require("path");
const { pathToFileURL } = require("url");
const { readGeneratorSources, loadBingoSync } = require("../load_generator");
const { makeCardFor } = require("../board");

const ROOT = path.join(__dirname, "..");
const SITE = path.join(__dirname, "site");
const GENERATED = path.join(__dirname, "generated", "bingosync.mjs");

// BingoSync's generator assigns variables it never declares (its base sets bingoGenerator, and uses x, y and value).
// That's fine in a plain script (they become globals) but an error in a module, which is always strict, so the
// wrapper declares them; the generator's own code is left as it is. The build checks the result against Node's
// plain-script run before writing anything.
const UNDECLARED = ["bingoGenerator", "x", "y", "value"];
const REQUIRE_LINE = 'bingoGenerator = require("./generators/generator_bases/srl_generator_v5_blackout.js");';

function generatorModule({ generator, base }) {
  if (!generator.includes(REQUIRE_LINE)) throw new Error("BingoSync's generator file isn't shaped as expected.");
  return [
    "// Generated by cloudflare/build.js from BingoSync's Beta Quest generator (https://github.com/kbuzsaki/bingosync;",
    "// load_generator.js has the pinned commit and hashes). Not committed.",
    `let ${UNDECLARED.join(", ")};`,
    "const module = { exports: {} };",
    "(function (module, exports) {",
    base,
    "})(module, module.exports);",
    "const generatorBase = module.exports;",
    generator.replace(REQUIRE_LINE, "bingoGenerator = generatorBase;"),
    "export { bingoGenerator, bingoList };",
    "",
  ].join("\n");
}

// (Room links /r/<code> and /play are the same page: wrangler.toml's not_found_handling serves index.html for them.)
const HEADERS = [
  "/*",
  "  Referrer-Policy: no-referrer", // room links carry the room code
  "  X-Content-Type-Options: nosniff",
  "/rules.js",
  "  Cache-Control: no-cache",
  "",
].join("\n");

async function main() {
  // The generator module, checked: the same cards as BingoSync's code run as a plain script, on 500 seeds per size.
  const text = generatorModule(readGeneratorSources());
  const tmp = `${GENERATED}.check.mjs`;
  fs.mkdirSync(path.dirname(GENERATED), { recursive: true });
  fs.writeFileSync(tmp, text);
  try {
    const strict = makeCardFor(await import(pathToFileURL(tmp).href));
    const plain = makeCardFor(loadBingoSync());
    for (let k = 0; k < 500; k++) {
      const seed = String(1 + Math.floor((k * 999998) / 499));
      for (const size of [4, 5, 6]) {
        if (JSON.stringify(strict(seed, size)) !== JSON.stringify(plain(seed, size))) throw new Error(`The module's ${size}x${size} card for seed ${seed} differs from BingoSync's.`);
      }
    }
  } finally {
    fs.rmSync(tmp, { force: true });
  }
  fs.writeFileSync(GENERATED, text);

  // The site.
  fs.rmSync(SITE, { recursive: true, force: true });
  fs.mkdirSync(SITE, { recursive: true });
  fs.copyFileSync(path.join(ROOT, "fog.html"), path.join(SITE, "index.html"));
  const rules = fs.readFileSync(path.join(ROOT, "fog_logic.js"), "utf8");
  fs.writeFileSync(path.join(SITE, "rules.js"), `(function () { var module = { exports: {} };\n${rules}\nwindow.FogRules = module.exports; })();\n`);
  fs.writeFileSync(path.join(SITE, "_headers"), HEADERS);
  console.log(`built ${path.relative(ROOT, SITE)} and ${path.relative(ROOT, GENERATED)} (the generator module matches BingoSync's cards)`);
}

main().catch((e) => { console.error(e.message); process.exit(1); });
